def load(key: str) -> tuple[str, str]:
    for p in SRC.glob("*.txt"):
        n = unicodedata.normalize("NFC", p.stem)
        if key in n:
            return n, p.read_text(encoding="utf-8")
    raise SystemExit(f"見つからない: {key}")


def tidy(body: str) -> str:
    lines = body.split("\n")
    out: list[str] = []
    for ln in lines:
        # 節の見出しは太字の1行にする（章 ## と条 ### の間）
        m = re.match(r"^\s*(第\s*[0-9０-９]+\s*節)\s*(.*)$", ln)
        if m and len(ln) < 40:
            title = re.sub(r"\s+", "", m.group(2))
            num = unicodedata.normalize("NFKC", re.sub(r"\s+", "", m.group(1)))
            out += ["", f"**{num}　{title}**"]
            continue
        # 同じ条の見出しが続けて2回出るもの（原本の重複）は1つにする
        if ln.startswith("### ") and out and ln in out[-3:]:
            continue
        out.append(ln)
    s = "\n".join(out)
    return re.sub(r"\n{3,}", "\n\n", s).strip() + "\n"


def strip_title(body: str) -> str:
    """先頭の表題の行（「契約社員就業規則」「給　与　規　程」など）を外す。表題は # 見出しで付け直す。"""
    first, _, rest = body.partition("\n")
    if not first.startswith(("#", "（", "|")) and len(first) < 30:
        return rest.lstrip("\n")
    return body


def split_chapters(body: str, cut: int) -> tuple[str, str]:
    """第 cut 章の見出しの前で2つに分ける。"""
    m = re.search(rf"^## 第{cut}章", body, re.M)
    assert m, cut
    return body[: m.start()], body[m.start():]


def articles(body: str) -> str:
    nums = [int(x) for x in re.findall(r"^### 第(\d+)条", body, re.M)]
    return f"第{nums[0]}〜{nums[-1]}条" if nums else ""


