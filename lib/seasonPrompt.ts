// 部門ごとの追記（このモード専用）。該当しない部門は共通プロンプトのみ。
const SEASON_DEPT_SUPPLEMENTS: Record<string, string> = {
  RED個別: `- RED個別は講師に大学生スタッフが多い。「その他振り返り」では、スタッフの研修項目の進捗・シフト運営についても一度確認する。
  スタッフ個人の評価には深入りせず、件数・傾向で扱う。`,
  '総務・人事・支援・管理': `- 管理部門は校舎・数値を持たない場合がある。その場合は校舎の確認と数値の復唱を飛ばし、振り返りから始めてよい。`,
};

// numbersText は「数値報告」メニュー（講習期）の登録内容（lib/numberReports.ts の formatEntries）。
// season は既定の対象講習期（例「2026年夏期」。lib/numberReports.ts の defaultPeriod）。
export function buildSeasonPrompt(dept: string, name: string, numbersText: string, season: string): string {
  const supplement = SEASON_DEPT_SUPPLEMENTS[dept] ? `${SEASON_DEPT_SUPPLEMENTS[dept]}\n` : '';
  const campuses = campusesFor(dept);
  const instructions = SEASON_INSTRUCTIONS
    .replace('{{部門別追記}}', supplement)
    .replace('{{提出の流れ}}', SUBMIT_FLOW)
    .replace('{{数値データ}}', numbersText || '（この部門の講習期の数値報告はまだ登録されていません）')
    .replace(
      '{{校舎案内}}',
      campuses.length
        ? `この部門の校舎（${campuses.join('／')}）を選択肢として示し、この中から選んでもらう。`
        : 'この部門は校舎の登録が無いため、校舎名は自由に答えてもらう。',
    )
    .replace(/\{\{講習期\}\}/g, season)
    .replace(/\{\{事業部\}\}/g, dept || '（事業部）')
    .replace(/\{\{担当\}\}/g, name || '（担当）');
  return withCompanyKnowledge(instructions);
}
