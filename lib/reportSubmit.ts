// 会議AI（月次報告・講習の結果報告）の「報告完了」での自動保存。
// 中間報告（lib/progressPrompt.ts）と同じ作り：
//   AI は下書きを見せ、報告者が「報告完了」と送ったときだけ「＝＝＝ …（ここから）＝＝＝」の囲みを出す。
//   画面（components/ChatUI.tsx）はその囲みを見つけたら /api/report へ送り、会議ドキュメントへ転記する
//   （成功事例の全社集約も /api/report 側で同時に行う）。
// ★囲みの書式を変えるときは、各プロンプトの最終出力と extractFinalBlock を両方直すこと。

// 各プロンプトの末尾に差し込む「提出の流れ」。
export const SUBMIT_FLOW = `【提出の流れ（厳守）】報告文は「貼り付け」ではなく、「報告完了」の一言で自動保存する。
1. 下書きの提示：全項目が揃ったら、最終出力と同じ内容を「＝＝＝」の囲み行を付けずに「下書き」として提示し、必ずこう添える：
   「この内容で提出する場合は、入力欄に『報告完了』と送ってください。修正があれば教えてください。」
   この段階では「＝＝＝ …（ここから）＝＝＝」「＝＝＝ …（ここまで）＝＝＝」の行は絶対に出力しない。
2. 修正を頼まれたら、直した下書きを提示し直し、同じ一文を添える。
3. 確定：下書きを提示した後に報告者が「報告完了」と送ったときだけ、最終出力の囲みブロックを出力する（前後に余計な文章を付けない）。
   この囲みが出力された時点で、システムが自動で会議ドキュメントへ保存する。
   下書きをまだ見せていない段階で「報告完了」と言われた場合は、囲みを出さずに、まず下書きを提示する。
4. 保存の後に修正を求められた場合は、直した下書きを提示し、もう一度「報告完了」を待つ（送り直すと、直した内容が改めて保存される）。`;

const BLOCK = /＝＝＝[^\n]*（ここから）＝＝＝[\s\S]*?＝＝＝[^\n]*（ここまで）＝＝＝/;

// AI の回答から確定ブロック（囲みを含む）を取り出す。無ければ null。
export function extractFinalBlock(text: string): string | null {
  const m = text.match(BLOCK);
  return m ? m[0].trim() : null;
}

// 報告者の発言が「報告完了」か（空白・句読点の揺れは許す）。
export function isSubmitCommand(text: string): boolean {
  return text.replace(/[\s　。．.！!]/g, '').includes('報告完了');
}
