// 月次報告プロンプト（会議AI「月次報告」モード。通常期の毎月の結果報告）
// 講習の結果報告（lib/seasonPrompt.ts）と同じ作りで、
// 数値は「数値報告」メニュー（lib/numberReports.ts の月次）で登録されたものを読み取るだけで、対話では尋ねない。
// 対話では「その月の計画の実践度合い（%）と理由」と「成功事例」を聞き取る。会議日は毎月の報告なので聞かない。
// ★挙動を直す場合はこのファイルを編集 → git push（Vercel が自動再デプロイ）。
// ★「■ 成功事例（全体共有）」の書式は lib/successCases.ts の抽出と対になっている。変えるときは両方直すこと。

