// 部門ごとの追記（このモード専用）。該当しない部門は共通プロンプトのみ。
const MONTHLY_DEPT_SUPPLEMENTS: Record<string, string> = {
  RED個別: `- RED個別は講師に大学生スタッフが多い。計画の実践度合いの確認では、スタッフの研修項目の進捗・シフト運営についても一度確認する。
  スタッフ個人の評価には深入りせず、件数・傾向で扱う。`,
  高等部: `- 高等部は東進衛星予備校（映像授業）を運用している。東進関連の数字（受講率など）は「その他、部門ごとのイベント等」に登録されていればそのまま転記する。`,
  '総務・人事・支援・管理': `- この部門は校舎の代わりにグループ（管理・支援・経理）で報告する。A の「担当グループ」はこの3つから選んでもらう。
- 生徒数・入会・体験は無い。数値は「数値報告（自由記述）」の1項目だけで、担当業務で管理している数値が書かれている。
  A では登録された自由記述をそのまま復唱・転記し、書かれていない数値を尋ねたり補ったりしない。
- 抜け漏れ確認の分野は、担当業務（総務・人事・支援・経理 など）に合わせて置き換えて確認する。
- 数値を担当していない職員は B（行動目標と結果）でよい。A を選んでも数値が無いと言われた場合は、数値の確認を飛ばして計画の実践度合いから始めてよい。`,
};

// numbersText は「数値報告」メニュー（月次）の登録内容（lib/numberReports.ts の formatEntries）。
// month は既定の対象月（例「2026年9月分」。lib/numberReports.ts の defaultPeriod）。
export function buildMonthlyPrompt(dept: string, name: string, numbersText: string, month: string): string {
  const supplement = MONTHLY_DEPT_SUPPLEMENTS[dept] ? `${MONTHLY_DEPT_SUPPLEMENTS[dept]}\n` : '';
  const campuses = campusesFor(dept);
  const unit = unitLabel(dept);
  const monthLabel = month.replace(/分$/, ''); // 「2026年9月分」→「2026年9月」
  const instructions = MONTHLY_INSTRUCTIONS
    .replace('{{部門別追記}}', supplement)
    .replace('{{タブ確認ルール}}', modeCheckRule('monthly'))
    .replace('{{タブ確認}}', modeCheckLine('monthly'))
    .replace('{{提出の流れ}}', SUBMIT_FLOW)
    .replace('{{数値データ}}', numbersText || '（この部門の月次の数値報告はまだ登録されていません）')
    .replace(
      '{{校舎案内}}',
      campuses.length
        ? `この部門の${unit}（${campuses.join('／')}）を選択肢として示し、この中から選んでもらう。`
        : `この部門は${unit}の登録が無いため、${unit}名は自由に答えてもらう。`,
    )
    .replace(/\{\{単位\}\}/g, unit)
    .replace(/\{\{対象月名\}\}/g, monthLabel.replace(/^\d+年/, ''))
    .replace(/\{\{対象月\}\}/g, monthLabel)
    .replace(/\{\{事業部\}\}/g, dept || '（事業部）')
    .replace(/\{\{担当\}\}/g, name || '（担当）');
  return withCompanyKnowledge(instructions);
}
