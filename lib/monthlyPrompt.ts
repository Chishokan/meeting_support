const ACTION_NO_NUMBERS = `- この部門は数値報告をしない。数値を尋ねたり、報告文に数値の欄を作ったりしない
  （報告者が行動の結果として件数などを述べた場合は、「行動内容と結果」の中にそのまま書く）。`;

// 数値報告をする部門（LEC）向け。数値は登録済みのものを転記するだけで、会話では扱わない。
const ACTION_NUMBERS = `- 数値は「数値報告」メニュー（月次）で登録されたものを使う。あなたが数値を尋ねたり、会話の中で復唱したりはしない。
- 対象月が決まったら、【登録済みの数値報告】のうち▼の対象月が一致するもの（複数あればすべて）を、最終出力の「■ 数値報告」へ番号の並びのまま転記する。別の月の数値を流用しない。
- 対象月の数値が登録されていない場合は、対象月が決まった直後の発言で一度だけ
  「この月の数値はまだ『数値報告』メニュー（月次）に登録されていません。登録すると報告文に入ります（このまま報告を続けて構いません）。」
  と伝えて、そのまま進める。最終出力の「■ 数値報告」は「未登録」とする。
- 数値は登録のとおり正確に転記する。計算・推測して数字を作らない（達成率・前年比も書き足さない）。「未集計」はそのまま載せる。
- 会話の中で数値の訂正を申し出られた場合は、報告文を書き換えず、「『数値報告』メニューで登録し直してください」と案内する。`;

const ACTION_NUMBERS_SECTION = `■ 数値報告
（【登録済みの数値報告】の対象月の内容を、番号の並びのままそのまま転記する。登録が無ければ「未登録」）

`;

function buildActionPrompt(dept: string, name: string, numbersText: string, monthLabel: string): string {
  const withNumbers = !NO_NUMBER_DEPTS.includes(dept);
  const numbersData = withNumbers
    ? `\n【登録済みの数値報告】※「数値報告」メニュー（月次）から登録された内容。▼の後ろが「対象月／部門／校舎」。ここから読み取って使い、数値を尋ねない。\n${
        numbersText || '（この部門の月次の数値報告はまだ登録されていません）'
      }\n`
    : '';
  const instructions = ACTION_INSTRUCTIONS
    .replace('{{数値の扱い}}', withNumbers ? ACTION_NUMBERS : ACTION_NO_NUMBERS)
    .replace('{{数値欄}}', withNumbers ? ACTION_NUMBERS_SECTION : '')
    .replace('{{タブ確認ルール}}', modeCheckRule('monthly'))
    .replace('{{タブ確認}}', modeCheckLine('monthly'))
    .replace('{{提出の流れ}}', SUBMIT_FLOW)
    .replace(/\{\{対象月\}\}/g, monthLabel)
    .replace(/\{\{事業部\}\}/g, dept || '（事業部）')
    .replace(/\{\{担当\}\}/g, name || '（担当）')
    // 登録内容は最後に差し込む（中の文字が置き換えの対象にならないように。「$」も関数で渡してそのまま入れる）。
    .replace('{{数値データ}}', () => numbersData);
  return withCompanyKnowledge(instructions);
}

// numbersText は「数値報告」メニュー（月次）の登録内容（lib/numberReports.ts の formatEntries）。
// month は既定の対象月（例「2026年9月分」。lib/numberReports.ts の defaultPeriod）。
export function buildMonthlyPrompt(dept: string, name: string, numbersText: string, month: string): string {
  const monthLabel = month.replace(/分$/, ''); // 「2026年9月分」→「2026年9月」
  if (ACTION_REPORT_DEPTS.includes(dept)) return buildActionPrompt(dept, name, numbersText, monthLabel);
  const supplement = MONTHLY_DEPT_SUPPLEMENTS[dept] ? `${MONTHLY_DEPT_SUPPLEMENTS[dept]}\n` : '';
  const campuses = campusesFor(dept);
  const instructions = MONTHLY_INSTRUCTIONS
    .replace('{{部門別追記}}', supplement)
    .replace('{{タブ確認ルール}}', modeCheckRule('monthly'))
    .replace('{{タブ確認}}', modeCheckLine('monthly'))
    .replace('{{提出の流れ}}', SUBMIT_FLOW)
    .replace('{{数値データ}}', numbersText || '（この部門の月次の数値報告はまだ登録されていません）')
    .replace(
      '{{校舎案内}}',
      campuses.length
        ? `この部門の校舎（${campuses.join('／')}）を選択肢として示し、この中から選んでもらう。`
        : 'この部門は校舎の登録が無いため、校舎名は自由に答えてもらう。',
    )
    .replace(/\{\{対象月名\}\}/g, monthLabel.replace(/^\d+年/, ''))
    .replace(/\{\{対象月\}\}/g, monthLabel)
    .replace(/\{\{事業部\}\}/g, dept || '（事業部）')
    .replace(/\{\{担当\}\}/g, name || '（担当）');
  return withCompanyKnowledge(instructions);
}
