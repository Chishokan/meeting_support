type Args = { dept: string; name: string; policy: string; index: string; tasks?: string; images?: boolean };

// 画像を作る道具（generate_image）があるときだけ書く（Google の API キーが無いときは、作れると言わないように）
const IMAGE_LINE = `- 画像の作成：generate_image（チラシ・ポスター・サイネージの画像、スライドの挿絵。頼まれたときだけ。OpenAI か Google の画像生成AI）。
  作った画像は画面に出て、次の質問にも付け直されるので、「文字を大きく」などと頼まれたら source に前の画像のファイル名を入れて直す。
  画像の中の日本語は崩れることがあるので、日付・料金・電話番号は原稿と照らし合わせてもらう。実在の人物の顔・他社のロゴ・QRコードは描かせない。
`;
// 画像を作る道具が無いとき（2026-11-19 から API での画像生成を一旦停止。2026-11-21 から「調整中」と職員に伝える）：画像・挿絵・チラシなどの制作は NEP事業部に依頼する
const NO_IMAGE_LINE = `- 画像：智翔館AI は作らない（GPT・Gemini の API を使った画像生成は調整中）。画像・イラスト・スライドの挿絵や背景・チラシやポスターの画像を頼まれたら、
  最初に「GPT・Gemini（API）を使った画像生成は調整中のため、いまは使えません」と1文で伝えてから、
  propose_nep_request で NEP事業部への作成依頼の案を画面に出す。案には、作るもの・用途・大きさや枚数・中身（何を描くか・雰囲気・配色・構図）・
  入れないもの・納品希望日を入れる（会話で分からない項目は「未定（相談）」にし、回答で職員に確かめる）。
  職員が［この内容でNEPへ作成依頼を出す］を押したときだけ送られるので、「送りました」と言い切らず「下のボタンで送ってください」と伝える。
`;

export function buildChishokanAiPrompt({ dept, name, policy, index, tasks, images }: Args): string {
  // 置換文字列の $ を特別扱いさせないよう、関数で渡す。
  // 枠の差し込み場所を先に埋め、資料の中身（回答方針・索引）は最後に入れる（資料の中の {{…}} を誤って置き換えないように）。
  const text = FRAME.replace('{{週}}', () => weekRanges())
    .replace('{{画像}}', () => (images ? IMAGE_LINE : NO_IMAGE_LINE))
    .replace('{{部門}}', () => dept)
    .replace('{{名前}}', () => name)
    .replace('{{作業一覧}}', () => tasks?.trim() || '（手順書はまだありません）')
    .replace('{{回答方針}}', () => policy.trim() || '（回答方針のファイルが読めませんでした）')
    .replace('{{索引}}', () => index.trim() || '（索引のファイルが読めませんでした。list_dir で探す）');
  return withCompanyKnowledge(text);
}
