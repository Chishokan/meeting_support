type RiskSpec = Partial<Record<ScaleCode, [number | null, number | null]>>; // [注意, 要注意]

function buildRule(role: Role, weights: Partial<Record<ScaleCode, number>>, risks: RiskSpec): RoleRule {
  const scales = {} as Record<ScaleCode, ScaleRule>;
  for (const s of SEED_SCALES) {
    const o = ROLE_NOTES[role][s.code] ?? {};
    const [caution, alert] = risks[s.code] ?? [null, null];
    scales[s.code] = {
      weight: weights[s.code] ?? 0,
      caution,
      alert,
      highNote: o.high ?? COMMON_NOTES[s.code].high,
      lowNote: o.low ?? COMMON_NOTES[s.code].low,
    };
  }
  return { gradeA: 60, gradeB: 40, lieAt: 7, minAvgSec: 1, highAt: 7, lowAt: 3, scales };
}

