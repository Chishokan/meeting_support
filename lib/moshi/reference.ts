function parseSchools(src: string): RefSchool[] {
  const out: RefSchool[] = [];
  for (const line of src.split('\n')) {
    const p = line.trim().split('|');
    if (p.length !== 6) continue;
    out.push({ ref: p[0], name: p[1], bDev: Number(p[2]), rule: p[3], bScore: Number(p[4]), max: Number(p[5]) });
  }
  return out;
}

