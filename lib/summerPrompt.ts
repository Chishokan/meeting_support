// 募集／継続／成績で確認する項目（部門共通のベース）。
// ★聞く項目を増減したいときはここを編集する。
function itemsFor(dept: string) {
  const recruit = [
    '夏期講習会の外部生募集（申込／実施）',
    '体験・面談（申込／実施）',
    '入塾者数',
    '紹介（SYS／HYS／BS）',
    '募集イベント・キャンペーンの人数（キャンペーン名 ○/○名）',
  ];
  const retention = [
    '夏期講習会後の継続（継続者数・継続率）',
    '退塾者数',
    '9月時点の在籍数',
  ];
  const grades = [
    '夏の模試・テストの結果（平均点・偏差値・判定など）',
    '成績回収：○/○名（実績/母数）',
    '目標達成者数',
  ];
  // 売上は数値必須部門のみ（小中等部は社長指示により含めない）。
  if (NUMERIC_DEPTS.includes(dept) && !NO_SALES_DEPTS.includes(dept)) {
    recruit.push('夏期講習会の売上');
  }
  if (dept === '高等部') {
    recruit.push('無料招待講習など東進の新規（申込／実施）');
    grades.push(
      '学年別の実質受講率（高1／高2／高3）',
      '受講進捗（受講コマ数の進み・修了／遅れ）',
      '担任・担任助手による面談の実施状況',
    );
  }
  return { recruit, retention, grades };
}

function bullets(items: string[]): string {
  return items.map((s) => `　・${s}`).join('\n');
}

// 部門ごとの追記（このモード専用）。該当しない部門は共通プロンプトのみ。
const SUMMER_DEPT_SUPPLEMENTS: Record<string, string> = {
  RED個別: `- RED個別は講師に大学生スタッフが多い。「その他振り返り」では、スタッフの研修項目の進捗・シフト運営についても一度確認する。
  スタッフ個人の評価には深入りせず、件数・傾向で扱う。`,
  '総務・人事・支援・管理': `- 管理部門は募集・継続・成績の数値を持たない場合がある。該当しない区分は「該当なし」でよい。
  担当領域（総務・人事・支援・管理）で把握している夏の実績・件数があれば「その他振り返り」に記載する。`,
};

export function buildSummerPrompt(dept: string, name: string): string {
  const { recruit, retention, grades } = itemsFor(dept);
  const supplement = SUMMER_DEPT_SUPPLEMENTS[dept] ? `${SUMMER_DEPT_SUPPLEMENTS[dept]}\n` : '';
  return SUMMER_INSTRUCTIONS
    .replace('{{部門別追記}}', supplement)
    .replace('{{募集項目}}', bullets(recruit))
    .replace('{{継続項目}}', bullets(retention))
    .replace('{{成績項目}}', bullets(grades))
    .replace(/\{\{事業部\}\}/g, dept || '（事業部）')
    .replace(/\{\{担当\}\}/g, name || '（担当）');
}
