// 夏の数値報告で確認する項目（全部門共通・この順番で尋ねる）。
// ★聞く項目を増減したいときはここを編集する。
const NUMBER_ITEMS = [
  '夏期講習会（招待）の外部生募集：申込／目標／昨年',
  '外部生の継続面談（入会面談）の実施数：○名',
  '外部生の継続：継続数／昨年の継続数／昨年の母数',
  '8月模試の外部生：今年／昨年／目標',
  '生徒数：9月現在／昨年9月',
  '通知表回収（新規入会者を含む）：100% か、あと何名か',
];

// 「その他、夏の数字で報告が必要なもの」に添える部門別の例。
function otherNumberExamples(dept: string): string {
  const ex: string[] = [];
  if (NUMERIC_DEPTS.includes(dept) && !NO_SALES_DEPTS.includes(dept)) ex.push('夏期講習会の売上');
  if (dept === '高等部') ex.push('東進の受講率・受講進捗', '担任・担任助手の面談実施状況');
  return ex.length ? `（例：${ex.join('、')}）` : '';
}

function bullets(items: string[]): string {
  return items.map((s) => `　・${s}`).join('\n');
}

// 部門ごとの追記（このモード専用）。該当しない部門は共通プロンプトのみ。
const SUMMER_DEPT_SUPPLEMENTS: Record<string, string> = {
  RED個別: `- RED個別は講師に大学生スタッフが多い。「その他振り返り」では、スタッフの研修項目の進捗・シフト運営についても一度確認する。
  スタッフ個人の評価には深入りせず、件数・傾向で扱う。`,
  '総務・人事・支援・管理': `- 管理部門は募集・在籍などの数値を持たない場合がある。該当しない項目は「該当なし」でよい。
  担当領域（総務・人事・支援・管理）で把握している夏の実績・件数があれば「その他の数字」に記載する。`,
};

export function buildSummerPrompt(dept: string, name: string): string {
  const items = [...NUMBER_ITEMS, `その他、夏の数字で報告が必要なもの${otherNumberExamples(dept)}`];
  const supplement = SUMMER_DEPT_SUPPLEMENTS[dept] ? `${SUMMER_DEPT_SUPPLEMENTS[dept]}\n` : '';
  return SUMMER_INSTRUCTIONS
    .replace('{{部門別追記}}', supplement)
    .replace('{{数値項目}}', bullets(items))
    .replace(/\{\{事業部\}\}/g, dept || '（事業部）')
    .replace(/\{\{担当\}\}/g, name || '（担当）');
}
